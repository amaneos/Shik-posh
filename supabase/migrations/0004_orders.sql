-- ============================================================================
-- 0004_orders.sql — Orders + order items + the atomic order/stock function
--                  (STEP 5, part A: database foundation only, no UI).
--
-- Extends the STEP 1 catalog (0001_init.sql), the STEP 2 galleries
-- (0002_product_images.sql) and the STEP 3 inventory (0003_variants.sql).
-- One client store per Supabase project; applied via the project's SQL editor
-- or `supabase db push` alongside 0001–0003 (which are never edited).
--
-- Model (deliberately narrow — no payments, no dashboards, no coupons):
--
--   orders ─┬─ order_items (order_id → orders.id, ON DELETE CASCADE)
--           │      product_id → products.id          (history is PROTECTED:
--           │      variant_id → variants.id           products/variants cannot
--           │                                         be deleted while ordered)
--           └─ money is stored as INTEGER TOMAN (bigint), never floats.
--
--   Two independent status axes, both stored as the PERSIAN customer-facing
--   label (the same strings the UI shows — no translation table to drift):
--     • payment_status — «در انتظار پرداخت» / «پرداخت شده» / «ناموفق» /
--                        «بازگشت وجه»
--     • order_status   — «در انتظار پرداخت» / «پردازش سفارش» / «آماده ارسال» /
--                        «ارسال شده» / «تحویل داده شده» / «لغو شده»
--   A brand-new order starts on «در انتظار پرداخت» for BOTH axes. Which
--   transitions are legal is business logic (a later step); only the DOMAIN is
--   enforced here, so a typo'd status can never be written.
--
-- THE POINT OF THIS MIGRATION — overselling must be impossible:
--   `public.create_order_with_items(...)` inserts the order + its items and
--   decrements `variants.stock_quantity` in ONE PostgreSQL transaction. Every
--   decrement is a guarded UPDATE
--       update variants set stock_quantity = stock_quantity - qty
--        where id = <variant> and stock_quantity >= qty;
--   and ZERO affected rows raises an exception, which rolls the WHOLE order
--   back — no order row, no partial stock change. Two customers racing for the
--   last unit therefore cannot both succeed: the second UPDATE re-reads the
--   committed value and finds `stock_quantity >= qty` false.
--   The function is also the ONLY writer of prices: it re-reads
--   `coalesce(products.discount_price, products.base_price)`, the product title
--   and the colour/size/SKU from the database, so a tampered client cannot
--   influence what an order costs. The client sends only
--   `{ product_id, variant_id, quantity }`.
--
-- NOTE on transactions: every plpgsql FUNCTION already runs inside the caller's
-- transaction, and PostgreSQL REJECTS transaction control (BEGIN/COMMIT) inside
-- a function body ("cannot commit while a PL/pgSQL function is running"). The
-- atomicity guarantee here is therefore the implicit single transaction plus the
-- RAISE that aborts it — which is strictly SAFER than committing halfway (a
-- COMMIT would make a later failure leave a half-finished order behind). Callers
-- that want an explicit block simply do:
--     begin;
--       select public.create_order_with_items(...);
--     commit;
--
-- Money shape: the existing price columns in 0001_init.sql are `numeric`;
-- order money is `bigint` (integer toman) so an order total can never carry a
-- fractional toman. The function casts once, at the point where it reads the
-- price.
--
-- NO explicit GRANTs here — 0001–0003 add none either, and PostgreSQL grants
-- EXECUTE on new functions to PUBLIC by default. The auth/RLS step tightens
-- this to the app role.
-- NOTE: Row Level Security and policies are intentionally NOT added here — they
-- arrive with the auth/roles step. Until then these tables remain accessible via
-- the anon key; do not expose them publicly (an order row is personal data).
-- ============================================================================

-- ----------------------------------------------------------------------------
-- orders — one row per checkout submission (header + money + the two statuses)
-- ----------------------------------------------------------------------------
create table public.orders (
  id               uuid primary key default gen_random_uuid(),
  -- Customer-facing, human-readable reference (generated by the app:
  -- e.g. ORD-20260927-0001). UNIQUE = a duplicate submission can never create a
  -- second row with the same reference.
  order_number     text not null unique,
  customer_name    text not null,
  customer_phone   text not null,
  customer_email   text,                                   -- optional
  shipping_address text not null,
  notes            text,                                   -- optional, customer note
  -- Integer Toman. Both amounts are computed by the DB function from the live
  -- catalog — never sent by the client. No shipping/taxes in this step, so
  -- total_amount equals subtotal_amount (kept separate so shipping can be added
  -- without a migration of the shape).
  subtotal_amount  bigint not null default 0 check (subtotal_amount >= 0),
  total_amount     bigint not null default 0 check (total_amount >= 0),
  payment_status   text not null default 'در انتظار پرداخت' check (payment_status in (
    'در انتظار پرداخت', 'پرداخت شده', 'ناموفق', 'بازگشت وجه'
  )),
  order_status     text not null default 'در انتظار پرداخت' check (order_status in (
    'در انتظار پرداخت', 'پردازش سفارش', 'آماده ارسال', 'ارسال شده', 'تحویل داده شده', 'لغو شده'
  )),
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  -- An order with a blank reference / name / phone / address is unfulfillable
  -- and unsearchable — reject it at the DB (same style as 0003's blank checks).
  constraint orders_order_number_not_blank check (btrim(order_number) <> ''),
  constraint orders_customer_name_not_blank check (btrim(customer_name) <> ''),
  constraint orders_customer_phone_not_blank check (btrim(customer_phone) <> ''),
  constraint orders_shipping_address_not_blank check (btrim(shipping_address) <> '')
);

